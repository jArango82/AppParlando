  static List<PracticeExercise> byCategoryAndLevel(
    PracticeCategory category,
    String level, {
    int? limit,
    bool shuffle = true,
  }) {
    final filtered = all
        .where((e) => e.category == category && e.level == level)
        .toList();
    if (shuffle) {
      filtered.shuffle(Random());
    }
    if (limit != null && limit < filtered.length) {
      return filtered.take(limit).toList();
    }
    return filtered;
  }

  static int countFor(PracticeCategory category, String level) {
    return all
        .where((e) => e.category == category && e.level == level)
        .length;
  }
